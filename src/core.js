export function getSoundCuePlan(name, intensity = 1) {
  const strength = Math.min(1.6, Math.max(0.2, Number(intensity) || 1));
  const recipe = SOUND_CUE_RECIPES[name] || [];
  return recipe
    .map((layer) => ({
      ...layer,
      gain: Number((layer.gain * strength).toFixed(4)),
    }))
    .sort((a, b) => a.at - b.at);
}

